-- Initial database schema for the ZILENIX Technologies site.
-- Safe to apply to an existing project: creates missing tables and seeds only
-- fixed IDs that do not already exist.

create table if not exists public.services (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  promise text,
  sort_order integer not null default 0,
  visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.industries (
  id bigint generated by default as identity primary key,
  name text not null,
  description text,
  sort_order integer not null default 0,
  visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.faqs (
  id bigint generated by default as identity primary key,
  question text not null,
  answer text not null,
  sort_order integer not null default 0,
  visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.counters (
  id bigint generated by default as identity primary key,
  label text not null,
  value integer not null default 0,
  sort_order integer not null default 0,
  visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.testimonials (
  id bigint generated by default as identity primary key,
  name text,
  role text,
  company text,
  quote text,
  review text,
  sort_order integer not null default 0,
  visible boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.projects (
  id bigint generated by default as identity primary key,
  title text not null,
  description text,
  category text,
  tech text,
  status text not null default 'Draft',
  sort_order integer not null default 0,
  visible boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.knowledge_base (
  id bigint generated by default as identity primary key,
  question text not null,
  answer text not null,
  keywords text[] not null default '{}',
  sort_order integer not null default 0,
  visible boolean not null default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.contacts (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null,
  phone text,
  company text,
  service text,
  industry text,
  details text not null,
  lead_status text not null default 'New',
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.zilenix_leads (
  id bigint generated by default as identity primary key,
  name text not null,
  email text not null default '',
  phone text not null default '',
  service text not null default '',
  description text not null,
  lead_status text not null default 'New',
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create index if not exists contacts_created_at_idx on public.contacts (created_at desc);
create index if not exists projects_visibility_order_idx on public.projects (visible, sort_order);
create index if not exists services_visibility_order_idx on public.services (visible, sort_order);
create index if not exists industries_visibility_order_idx on public.industries (visible, sort_order);

-- All browser-facing reads and writes go through the API handlers. Keep direct
-- table access closed to anon/authenticated users; the server secret is used
-- only after each protected handler validates the user's auth token.
alter table public.services enable row level security;
alter table public.industries enable row level security;
alter table public.faqs enable row level security;
alter table public.counters enable row level security;
alter table public.testimonials enable row level security;
alter table public.projects enable row level security;
alter table public.knowledge_base enable row level security;
alter table public.contacts enable row level security;
alter table public.zilenix_leads enable row level security;

revoke all on public.services, public.industries, public.faqs, public.counters,
  public.testimonials, public.projects, public.knowledge_base, public.contacts,
  public.zilenix_leads from anon, authenticated;
grant all on public.services, public.industries, public.faqs, public.counters,
  public.testimonials, public.projects, public.knowledge_base, public.contacts,
  public.zilenix_leads to service_role;
grant usage, select on all sequences in schema public to service_role;

